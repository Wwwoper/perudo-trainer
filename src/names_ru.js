// names_ru.js — формы имён игроков для текстов тренажёра. Чистая логика, без DOM.
// Имена ботов берутся из закрытого списка, поэтому формы записаны словарём, а не вычисляются
// правилами: автоматическое склонение ошибается на редких именах и никнеймах. Для имени, которого
// в словаре нет, тексты строятся без склонения.
import { BOT_NAMES } from './bots.js';

/** Слово, которым тренажёр называет вас. */
export const YOU = 'Вы';

/** Имя → родительный падеж («ставка Андрея»). */
export const GENITIVE = Object.freeze({
  'Алексей': 'Алексея', 'Дмитрий': 'Дмитрия', 'Иван': 'Ивана', 'Сергей': 'Сергея', 'Николай': 'Николая',
  'Андрей': 'Андрея', 'Максим': 'Максима', 'Александр': 'Александра', 'Павел': 'Павла', 'Михаил': 'Михаила',
  'Мария': 'Марии', 'Ольга': 'Ольги', 'Анна': 'Анны', 'Елена': 'Елены', 'Татьяна': 'Татьяны',
  'Наталья': 'Натальи', 'Екатерина': 'Екатерины', 'Анастасия': 'Анастасии', 'Ирина': 'Ирины', 'Юлия': 'Юлии',
});

/**
 * Родительный падеж имени из словаря.
 * @param {string} name
 * @returns {string|null} null, если формы нет (незнакомое имя, никнейм, «Вы»)
 */
export function genitive(name) {
  const n = String(name ?? '').trim();
  return Object.hasOwn(GENITIVE, n) ? GENITIVE[n] : null;
}

/**
 * Чья ставка: «ваша ставка», «ставка Андрея»; для имени без формы без склонения: «ставка: Лис».
 * @param {string} name
 * @returns {string}
 */
export function bidOf(name) {
  const n = String(name ?? '').trim();
  if (n === YOU) return 'ваша ставка';
  const g = genitive(n);
  if (g) return `ставка ${g}`;
  return n ? `ставка: ${n}` : 'ставка';
}

/** Все имена бота, у которых нет формы в словаре (для теста: должно быть пусто). */
export function namesWithoutForm() {
  return BOT_NAMES.filter((n) => genitive(n) === null);
}
