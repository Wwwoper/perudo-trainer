// calc_text.js — пояснение к проценту в калькуляторе. Чистый модуль: без DOM.
//
// Один процент легко принять за шанс успеха «Не верю!». На самом деле это шанс, что ставка соперника верна;
// шанс успешной проверки — дополнение до 100 %. Расчёт идёт по вашим кубикам, чужие считаются случайными.

/**
 * Две строки пояснения к вероятности ставки.
 * @param {number} p вероятность, что ставка верна (0…1)
 * @param {(x: number) => string} fmt форматирование процента (как в остальном интерфейсе)
 * @returns {string[]} пустой массив, если вероятность не число из [0, 1]
 */
export function calcExplainLines(p, fmt) {
  if (typeof p !== 'number' || !Number.isFinite(p) || p < 0 || p > 1 || typeof fmt !== 'function') return [];
  return [
    `Ставка верна с шансом ${fmt(p)}.`,
    `«Не верю!» сработает с шансом ${fmt(1 - p)}.`,
  ];
}
