// trainer_stats.js — что стирает кнопка «Сбросить статистику тренажёра». Чистый модуль: без DOM и хранилища.
//
// Сбрасывается только то, что копит сам Тренажёр: счётчики решений (всего и по режимам) и его тема
// «торги с несколькими соперниками» (режим «Лестница ставок») в «Над чем поработать». Статистика упражнений,
// остальные темы («Над чем поработать» берёт их из партий и викторины) и сами партии остаются.

/** Метка темы «торги с несколькими соперниками» в byTag (её пишет только Тренажёр, режим «Лестница»). */
export const LADDER_TAG = 'ladder';

/** Вопрос в окне подтверждения: называет всё, что будет стёрто, и то, что не изменится. */
export const RESET_CONFIRM =
  'Сбросить статистику тренажёра, очередь повторов и тему «торги с несколькими соперниками» в «Над чем поработать»?\n\n' +
  'Упражнения, партии и остальные темы не меняются.';

/**
 * Обнуляет счётчики Тренажёра в профиле S (изменяет объект и возвращает его).
 * @param {{n?: number, good?: number, byMode?: object, byTag?: object}} S
 */
export function resetTrainerStats(S) {
  S.n = 0;
  S.good = 0;
  S.byMode = {};
  if (S.byTag && typeof S.byTag === 'object' && !Array.isArray(S.byTag)) delete S.byTag[LADDER_TAG];
  return S;
}
