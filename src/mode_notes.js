// Редкий ход не равен ошибке: решатель просто почти никогда его не выбирает.
export function deviationLabel(pr) {
  return pr < 0.05 ? 'редкий для решателя ход' : 'в рамках';
}
export function duelSessionText(stats) {
  return `Сессия: партий ${stats.games}, побед ${stats.wins}; ` +
    `редких для решателя ходов: ${stats.dev} из ${stats.moves}. Редкий ход — не обязательно ошибка.`;
}
